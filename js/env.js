/**
 * 运行时环境配置
 * --------------------------------------------------------------------------
 * 账号重置密钥、演示口令这类东西不该写死在业务代码里，更不能提交到公开
 * 仓库。做法是统一从 window.KJ_ENV 读，业务代码只保留兜底默认值，
 * 本地调试时什么都不用配也能直接跑。
 *
 * 实际部署可以走三条路，任选其一：
 *   1) 直接改本文件（简单，但改完别把真实口令推上去）；
 *   2) 由 CI / 部署平台在构建时注入 window.KJ_ENV；
 *   3) 新建 env.local.js 并在 index.html 里引在本文件之后，覆盖默认值。
 *
 * 模板见根目录 env.example.js 与《环境配置.txt》。
 */
window.KJ_ENV = Object.assign(
  {
    RESET_KEY: '',        // 账号重置密钥；留空时业务代码用兜底值
    DEMO_ADMIN_PASS: '',  // 演示管理员初始口令；留空时业务代码用兜底值
    LLM_API_KEY: ''       // 预留：外部大模型服务 Key（当前版本不调用任何外部服务）
  },
  window.KJ_ENV || {}
);
